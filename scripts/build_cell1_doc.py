doc = Document()

def set_cn(run, size=11, bold=False, color=None):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)

def heading(text, level=1):
    p = doc.add_heading("", level=level)
    r = p.add_run(text)
    set_cn(r, size={0: 20, 1: 15, 2: 13, 3: 12}.get(level, 11), bold=True)
    return p

def para(text, size=11, bold=False, indent=False, color=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_cn(r, size=size, bold=bold, color=color)
    if indent:
        p.paragraph_format.left_indent = Pt(18)
    return p

def bullet(text):
    p = doc.add_paragraph(style="List Bullet")
    r = p.add_run(text)
    set_cn(r, size=11)
    return p

